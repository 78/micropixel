int TextWidth(const char* text, int scale) {
    const int length = Length(text);
    return length == 0 ? 0 : (length * (kGlyphWidth + 1) - 1) * scale;
}

void BuildGlyphAtlas(uint8_t* atlas) {
    for (int index = 0; index < kGlyphAtlasBytes; ++index) {
        atlas[index] = 0U;
    }
    constexpr int kCount = static_cast<int>(sizeof(kGlyphs) / sizeof(kGlyphs[0]));
    for (int index = 0; index < kCount; ++index) {
        const int u0 = (index % kCellsPerRow) * kGlyphCell;
        const int v0 = (index / kCellsPerRow) * kGlyphCell;
        for (int row = 0; row < kGlyphHeight; ++row) {
            const uint8_t bits = kGlyphs[index].rows[row];
            for (int column = 0; column < kGlyphWidth; ++column) {
                if ((bits & (0x10 >> column)) != 0) {
                    atlas[(u0 + column) * kGlyphAtlasHeight + v0 + row] = 1U;
                }
            }
        }
    }
}

bool GlyphCell(char symbol, int& u0, int& v0) {
    const int index = FindIndex(symbol);
    if (index < 0) {
        return false;
    }
    u0 = (index % kCellsPerRow) * kGlyphCell;
    v0 = (index / kCellsPerRow) * kGlyphCell;
    return true;
}

