int Length(const char* text) {
    int length = 0;
    while (text[length] != '\0') {
        ++length;
    }
    return length;
}

int FindIndex(char symbol) {
    if (symbol >= 'a' && symbol <= 'z') {
        symbol = static_cast<char>(symbol - 'a' + 'A');
    }
    constexpr int kCount = static_cast<int>(sizeof(kGlyphs) / sizeof(kGlyphs[0]));
    for (int index = 0; index < kCount; ++index) {
        if (kGlyphs[index].symbol == symbol) {
            return index;
        }
    }
    return -1;
}

constexpr int kCellsPerRow = kGlyphAtlasWidth / kGlyphCell;
static_assert(sizeof(kGlyphs) / sizeof(kGlyphs[0]) <= kCellsPerRow * (kGlyphAtlasHeight / kGlyphCell),
              "glyph atlas too small");

